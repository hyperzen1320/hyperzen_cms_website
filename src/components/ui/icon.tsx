export const ICON_NAMES = Object.keys(ICONS).sort();

export function Icon({
  name,
  className,
  strokeWidth = 1.6,
}: {
  name?: string | null;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = (name && ICONS[name]) || Sparkles;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden="true" />;
}
